import React, { useEffect, useState } from "react";
import { Admin, DataProvider, Resource } from "react-admin";
import buildGraphQLProvider from "./data-provider/graphqlDataProvider";
import { theme } from "./theme/theme";
import Login from "./Login";
import "./App.scss";
import Dashboard from "./pages/Dashboard";
import { HospitalList } from "./hospital/HospitalList";
import { HospitalCreate } from "./hospital/HospitalCreate";
import { HospitalEdit } from "./hospital/HospitalEdit";
import { HospitalShow } from "./hospital/HospitalShow";
import { MedicalRecordList } from "./medicalRecord/MedicalRecordList";
import { MedicalRecordCreate } from "./medicalRecord/MedicalRecordCreate";
import { MedicalRecordEdit } from "./medicalRecord/MedicalRecordEdit";
import { MedicalRecordShow } from "./medicalRecord/MedicalRecordShow";
import { InsurancePlanList } from "./insurancePlan/InsurancePlanList";
import { InsurancePlanCreate } from "./insurancePlan/InsurancePlanCreate";
import { InsurancePlanEdit } from "./insurancePlan/InsurancePlanEdit";
import { InsurancePlanShow } from "./insurancePlan/InsurancePlanShow";
import { UserList } from "./user/UserList";
import { UserCreate } from "./user/UserCreate";
import { UserEdit } from "./user/UserEdit";
import { UserShow } from "./user/UserShow";
import { jwtAuthProvider } from "./auth-provider/ra-auth-jwt";

const App = (): React.ReactElement => {
  const [dataProvider, setDataProvider] = useState<DataProvider | null>(null);
  useEffect(() => {
    buildGraphQLProvider
      .then((provider: any) => {
        setDataProvider(() => provider);
      })
      .catch((error: any) => {
        console.log(error);
      });
  }, []);
  if (!dataProvider) {
    return <div>Loading</div>;
  }
  return (
    <div className="App">
      <Admin
        title={"HealthConnect Backend"}
        dataProvider={dataProvider}
        authProvider={jwtAuthProvider}
        theme={theme}
        dashboard={Dashboard}
        loginPage={Login}
      >
        <Resource
          name="Hospital"
          list={HospitalList}
          edit={HospitalEdit}
          create={HospitalCreate}
          show={HospitalShow}
        />
        <Resource
          name="MedicalRecord"
          list={MedicalRecordList}
          edit={MedicalRecordEdit}
          create={MedicalRecordCreate}
          show={MedicalRecordShow}
        />
        <Resource
          name="InsurancePlan"
          list={InsurancePlanList}
          edit={InsurancePlanEdit}
          create={InsurancePlanCreate}
          show={InsurancePlanShow}
        />
        <Resource
          name="User"
          list={UserList}
          edit={UserEdit}
          create={UserCreate}
          show={UserShow}
        />
      </Admin>
    </div>
  );
};

export default App;
